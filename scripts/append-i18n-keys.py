def append_keys_to_dict(filepath, keys_dict):
    """Append new keys to a TypeScript dictionary file."""
    with open(filepath) as f:
        content = f.read()
    
    # Find the closing }; and insert before it
    # First check which keys already exist
    existing_keys = set()
    for key in keys_dict:
        if f'"{key}"' in content:
            existing_keys.add(key)
    
    new_keys = {k: v for k, v in keys_dict.items() if k not in existing_keys}
    
    if not new_keys:
        print(f"  No new keys needed for {filepath}")
        return 0
    
    # Build the entries string
    entries = []
    for key in sorted(new_keys.keys()):
        val = new_keys[key].replace('"', '\\"')
        entries.append(f'  "{key}": "{val}",')
    
    entries_str = '\n'.join(entries)
    
    # Insert before the final };
    content = content.rstrip()
    if content.endswith('};'):
        content = content[:-2] + '\n' + entries_str + '\n};\n'
    elif content.endswith('}'):
        content = content[:-1] + '\n' + entries_str + '\n};\n'
    
    with open(filepath, 'w') as f:
        f.write(content)
    
    print(f"  Added {len(new_keys)} keys to {filepath}")
    return len(new_keys)

